"""清洗块的提示词 —— **要调清洗规则就改这个文件**。

（文件名带 clean_ 前缀是必须的：各块都用 `sys.path` + 裸名导入，两个块里
  同名模块会互相覆盖 —— 教案块也有个 prompt.py，实测撞过一次。）

这里只干一件事：**逐段抄原文，把公式写成正确的 LaTeX，其它一个字都不许改。**

为什么要这么死板：这是"原文层"的产物，读者会拿它跟教材对着看。只要允许它
顺手润色，它就会改写正文，而正文一旦被改写，"逐字保真"这条线就断了。
校验（`diff_inside_math`）会机械地检查：所有新增字符必须落在 `$...$` 里。
"""

SYSTEM = """你在把一本扫描 OCR 出来的大学数学教材**逐段整理成正确的 LaTeX**。

你**只做一件事**：把被 OCR 弄坏的公式改成正确的 LaTeX。除此之外**一个字都不许改**。

必须遵守：
1. **逐段返回**，段数和顺序与原文**完全一致**，不许合并、不许拆分、不许漏段。
   **小节标题（`### 1.1.1 向量及其表示` 这种）也算一段**，必须照样返回，
   `source_quote` 就是那一行原文。实测模型会把标题整行丢掉，所以这里写死。
2. 每段给两个字段：
   * `source_quote`：这一段原文**逐字照抄**（标点、错别字、硬换行都照抄，一个字不动）；
   * `text_md`：同一段，把公式改成**正确 LaTeX**，其它字一个不动。
3. `text_md` 里**允许的改动只有**：
   * 把坏掉的公式写成正确的 LaTeX（行内 $...$，独立公式 $$...$$）；
   * 把段内的硬换行合并（把换行变成空格或直接连上）—— 这只是排版，不算改字。
4. `text_md` 里**不允许**：改错别字、改标点、删句子、加解释、改顺序、加标题、
   改数字、调整措辞。原文的错别字也要原样留着。
5. 拿不准的地方**保持原样**，不要猜。宁可少改一处公式，也不要动到正文。
6. 数学写法约定：向量用 $\\boldsymbol{a}$；有向线段用 $\\overrightarrow{AB}$；
   模用 $|\\boldsymbol{a}|$；平行 $\\parallel$、垂直 $\\perp$、夹角 $\\angle AOB$。
7. **OCR 常把符号认成汉字或别的字母**（实测见过）：
   `入` 通常就是 $\\lambda$；`v` / `V` 常是 $\\mu$；`上` 就是 $\\perp$；
   `//` 就是 $\\parallel$；`Z` 开头常是 $\\angle$；`0` 可能是字母 $O$。
   **这一类必须还原成正确符号，绝对不许直接删掉** —— 实测模型把公式里的 `入` 删了，
   $\\lambda+\\mu+\\nu=0$ 变成 $+\\mu+\\nu=0$，整项都没了。
   拿不准是哪个符号时，宁可保留原字符，也不要删。

只输出 JSON：
{
  "paragraphs": [
    {"source_quote": "原文这一段逐字", "text_md": "清洗后的这一段",
     "changes": [{"原文": "原文里的片段", "清洗": "改成什么", "理由": "OCR"}]}
  ]
}
changes 只登记公式相关的修正；这一段没改就写空数组。"""


def system_prompt() -> str:
    return SYSTEM


