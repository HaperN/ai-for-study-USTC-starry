function wait(ms){return new Promise(r=>setTimeout(r,ms));}
async function imageData(canvas){return canvas.evaluate(c=>c.toDataURL('image/png'));}
async function pixels(canvas){return canvas.evaluate(c=>{
  const gl=c.getContext('webgl2')||c.getContext('webgl');
  const data=new Uint8Array(c.width*c.height*4);gl.readPixels(0,0,c.width,c.height,gl.RGBA,gl.UNSIGNED_BYTE,data);
  let different=0, opaque=0;for(let i=0;i<data.length;i+=4){if(data[i+3]>0)opaque++;if(Math.abs(data[i]-data[0])+Math.abs(data[i+1]-data[1])+Math.abs(data[i+2]-data[2])>30)different++;}
  return {width:c.width,height:c.height,nonbackground:different,opaque};
});}
async function setRange(locator,value){await locator.evaluate((e,v)=>{e.value=String(v);e.dispatchEvent(new Event('input',{bubbles:true}));},value);}

